import 'server-only';
import { LIMITS, rateLimit } from '@/core/shared/http/rateLimit';
import { EngineMovePicker } from '@/modules/ai-engine/infrastructure/EngineMovePicker';
import { SupabasePlayerDirectory } from '@/modules/matchmaking/infrastructure/SupabasePlayerDirectory';
import { AnswerDraw } from '../../application/AnswerDraw';
import { BotTurn } from '../../application/BotTurn';
import { CreateAiGame } from '../../application/CreateAiGame';
import { GetAiLevels } from '../../application/GetAiLevels';
import { GetGameState } from '../../application/GetGameState';
import { GetMatchHistory } from '../../application/GetMatchHistory';
import { GetMove } from '../../application/GetMove';
import { GetPrediction } from '../../application/GetPrediction';
import { GetProfileHistory } from '../../application/GetProfileHistory';
import { MakeMove } from '../../application/MakeMove';
import { OfferDraw } from '../../application/OfferDraw';
import { PlayAiTurn } from '../../application/PlayAiTurn';
import { Rematch } from '../../application/Rematch';
import { Resign } from '../../application/Resign';
import { SuggestMove } from '../../application/SuggestMove';
import { Takeback } from '../../application/Takeback';
import { ChessJsRules } from '../../infrastructure/ChessJsRules';
import { SupabaseAiPlayers } from '../../infrastructure/SupabaseAiPlayers';
import { SupabaseArenaRepository } from '../../infrastructure/SupabaseArenaRepository';

// los bots de desarrollo juegan y contestan tablas únicamente con ENABLE_DEV_ROUTES=true
const devBots = process.env.ENABLE_DEV_ROUTES === 'true';
const repo = new SupabaseArenaRepository();
const players = new SupabasePlayerDirectory();
const ai = new SupabaseAiPlayers(devBots);
const rules = new ChessJsRules();
const engine = new EngineMovePicker();
export const makeMove = new MakeMove(repo, players, ai, rules);
export const getGameState = new GetGameState(repo, players, ai, devBots ? new BotTurn(repo) : undefined);
export const getMove = new GetMove(repo);
export const resign = new Resign(repo, players, ai);
export const offerDraw = new OfferDraw(repo, players, ai);
export const answerDraw = new AnswerDraw(repo, players, ai);
export const getMatchHistory = new GetMatchHistory(repo, players);
export const getProfileHistory = new GetProfileHistory(repo, players);
export const rematch = new Rematch(repo);
export const playAiTurn = new PlayAiTurn(repo, ai, engine, makeMove);
export const getAiLevels = new GetAiLevels(repo, players, ai);
export const createAiGame = new CreateAiGame(repo, players, ai, key => rateLimit(key, LIMITS.aiGames));
export const suggestMove = new SuggestMove(repo, rules, engine, key => rateLimit(key, LIMITS.aiMove));
export const getPrediction = new GetPrediction(repo, rules, engine, key => rateLimit(key, LIMITS.prediction));
export const takeback = new Takeback(repo);

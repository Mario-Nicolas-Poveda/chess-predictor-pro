/** Material + posición, en centipeones, desde el punto de vista del lado que mueve. */
export function evaluate(pos: Position): number {
  let s = 0;
  for (let i = 0; i < 64; i++) {
    const p = pos.b[i]; if (!p) continue;
    const v = PIECE_VALUE[p.t] + PST[p.t][p.c === 'w' ? i : i ^ 56]!;
    s += p.c === 'w' ? v : -v;
  }
  return pos.turn === 'w' ? s : -s;
}
